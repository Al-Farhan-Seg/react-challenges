/** Every challenge belonging to one source, in listed order. */
export function challengesBySource(sourceId) {
  return challenges.filter((challenge) => challenge.source === sourceId)
}

/**
 * Totals for the hero summary. These are derived from the array above so
 * they can never drift out of sync with the cards.
 */
export function getStats() {
  return {
    total: challenges.length,
    completed: challenges.filter((c) => c.status === 'completed').length,
    inProgress: challenges.filter((c) => c.status === 'in-progress').length,
  }
}
